     UIテスト(UIテスト\UIテスト.sln の 画面\販売価格変更履歴)を流す前に実行して、
     毎回同じ状態から試験データを作り直すために使う。

   ★注意★
     下の範囲に該当するレコードを問答無用で削除する。
