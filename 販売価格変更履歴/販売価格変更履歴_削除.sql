     車両仕入       車両仕入番号 142 〜 150、191・192(151〜190 は他画面が使っているので飛ばす)
     車両           車両番号     36557 〜 36565、36596・36597
     注文書表題     車両売上番号 30 〜 38、44
     車両仕入価格設定 上の車両仕入番号の変更履歴(テーブルがあるときだけ)
     汎用データ管理 データ区分 4005 のうち営業所0・担当者0 以外(ログインユーザー用に画面や車両買取の設定が作る行)。
                    毎回「所属営業所=本社」の初期値から始めるため。営業所0・担当者0 の行は残す(車両買取と共用)
   ====================================================================== */

