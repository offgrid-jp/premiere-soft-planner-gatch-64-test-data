BEGIN
    RAISERROR(N'本番DB(SP_USER_DAT)では実行できません。', 16, 1);
    RETURN;
END

IF OBJECT_ID(N'dbo.車両仕入価格設定') IS NOT NULL
    DELETE FROM [dbo].[車両仕入価格設定] WHERE [車両仕入番号] BETWEEN 142 AND 150 OR [車両仕入番号] IN (191, 192);
DELETE FROM [dbo].[注文書表題]   WHERE [車両売上番号] BETWEEN 30 AND 38 OR [車両売上番号] = 44;
DELETE FROM [dbo].[車両仕入]     WHERE [車両仕入番号] BETWEEN 142 AND 150 OR [車両仕入番号] IN (191, 192);
DELETE FROM [dbo].[車両]         WHERE [車両番号] BETWEEN 36557 AND 36565 OR [車両番号] IN (36596, 36597);
DELETE FROM [dbo].[汎用データ管理] WHERE [データ区分] = 4005 AND NOT ([営業所番号] = 0 AND [更新担当者番号] = 0);
