/* ======================================================================
   作業進捗_受付・予約一覧.sql で作成した試験データを削除する。

   用途:
     UIテスト(作業進捗_作業受付.UITests)を流す前に実行して、
     毎回まっさらな状態から試験データを作り直すために使う。
     出庫ボタン(No26)や完了ボタン(No27)はDBを書き換えるため、
     これが無いと2回目以降は前提が崩れて同じ結果にならない。

   ★注意★
     下の範囲に該当するレコードを問答無用で削除する。
     本番DBでは絶対に実行しないこと。試験用DBのみで使うこと。

     来店予約             入庫予約番号 1 〜 18
     車両                 車両番号     36602 〜 36606、36608、36609(36607 は車両買取の試験データなので消さない)
     車両仕入             車両仕入番号 187 〜 189
     作業進捗予実管理     上記の来店予約に紐づくもの
     作業進捗作業内容     同上
     作業進捗作業時間     同上(作業内容経由)
     作業進捗実績集計     同上
     汎用データ管理       データ区分 4030(条件保存)/4041(列幅保存) のうち
                          試験に使う営業所のもの

   削除は外部キーの向きに合わせて、子テーブルから順に行う。
   ====================================================================== */
IF DB_NAME() = N'SP_USER_DAT' BEGIN RAISERROR(N'本番DBでは流せません', 16, 1); RETURN; END

DECLARE @受付From int = 1;
DECLARE @受付To   int = 18;
DECLARE @車両From int = 36602;
DECLARE @車両To   int = 36606;
DECLARE @仕入From int = 187;
DECLARE @仕入To   int = 189;

-- 1) 作業進捗実績集計(作業時間・作業内容を参照している)
DELETE FROM [dbo].[作業進捗実績集計]
 WHERE [入庫予約番号] BETWEEN @受付From AND @受付To;

-- 2) 作業進捗作業時間(作業内容を参照している。入庫予約番号を持たないので作業内容経由で特定する)
DELETE FROM [dbo].[作業進捗作業時間]
 WHERE [作業内容番号] IN (
       SELECT [作業内容番号] FROM [dbo].[作業進捗作業内容]
        WHERE [入庫予約番号] BETWEEN @受付From AND @受付To);

-- 3) 作業進捗作業内容(予実管理を参照している)
DELETE FROM [dbo].[作業進捗作業内容]
 WHERE [入庫予約番号] BETWEEN @受付From AND @受付To;

-- 4) 作業進捗予実管理(来店予約を参照している)
DELETE FROM [dbo].[作業進捗予実管理]
 WHERE [入庫予約番号] BETWEEN @受付From AND @受付To;

-- 5) 来店予約
DELETE FROM [dbo].[来店予約]
 WHERE [入庫予約番号] BETWEEN @受付From AND @受付To;

-- 6) 車両仕入(車両を参照している)
DELETE FROM [dbo].[車両仕入]
 WHERE [車両仕入番号] BETWEEN @仕入From AND @仕入To;

-- 7) 車両
DELETE FROM [dbo].[車両]
 WHERE [車両番号] BETWEEN @車両From AND @車両To
    OR [車両番号] IN (36608, 36609);   -- 受付17・受付18の車両(36607 は車両買取の試験データ)

/* ----------------------------------------------------------------------
   8) 保存された検索条件と列幅(汎用データ管理)

   条件保存ボタン(No6)と列幅保存ボタン(No18)を押すと、ここにレコードが残る。
   残ったままだと次に画面を開いたときの初期値がその値になり、
   進捗状況チェックボックスの初期値(No10)と工程セットの初期値(No12)が
   「完了・出庫以外にチェック」「全て未選択」にならず、赤になる。

   消すのは試験に使う営業所のぶんだけにする。
   他の営業所・他の担当者が保存した設定まで巻き込まないため。
   営業所番号=0 は画面側が使うテンプレートなので残す。
   ---------------------------------------------------------------------- */
-- UITests がログインする担当者コード(AppHost.LoginUserId)。
-- 担当者番号ではなくコードで引くのは、共通データ.sql を入れていないDBでも
-- 同じログインユーザーを指せるようにするため(番号は環境ごとに違う)。
DECLARE @試験担当者コード nvarchar(10) = N'0001';
DECLARE @試験営業所 int = (SELECT TOP 1 [営業所番号] FROM [dbo].[担当者]
                            WHERE [担当者コード] = @試験担当者コード
                              AND [削除フラグ] = 0);

IF @試験営業所 IS NOT NULL
BEGIN
    DELETE FROM [dbo].[汎用データ管理]
     WHERE [データ区分] IN (4030, 4041)
       AND [営業所番号] = @試験営業所;
END
